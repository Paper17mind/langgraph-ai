"""
Express.js adapter — generates JavaScript files for an Express + Sequelize project using Jinja2 templates.

Phase 1: Sequelize models, Express routers, controllers (standard actions), Jest tests.
Phase 2: ai_inject_logic function bodies generated by LLM.
"""
import os
import re
import jinja2
from .base_adapter import BaseAdapter


_TYPE_MAP_SEQ = {
    "bigInteger": "DataTypes.BIGINT",
    "integer":    "DataTypes.INTEGER",
    "string":     "DataTypes.STRING",
    "text":       "DataTypes.TEXT",
    "boolean":    "DataTypes.BOOLEAN",
    "date":       "DataTypes.DATEONLY",
    "datetime":   "DataTypes.DATE",
    "decimal":    "DataTypes.DECIMAL",
    "float":      "DataTypes.FLOAT",
    "json":       "DataTypes.JSON",
}

TEMPLATE_DIR = os.path.join(os.path.dirname(__file__), "templates", "express")

env = jinja2.Environment(
    loader=jinja2.FileSystemLoader(TEMPLATE_DIR),
    autoescape=False
)


class ExpressAdapter(BaseAdapter):

    # ==================================================================
    # Phase 1 — Sequelize Models
    # ==================================================================

    def generate_models(self) -> dict[str, str]:
        files = {}
        template = env.get_template("model.js.jinja2")
        for model_def in self.schema["models"]:
            name = model_def["name"]
            
            # Map column types
            for col in model_def.get("columns", []):
                col["type"] = col.get("type", "string").upper()
                if col["type"] == "DATETIME": col["type"] = "DATE"
                if col["type"] == "DATE": col["type"] = "DATEONLY"
                
            js = template.render(model=model_def)
            files[f"src/models/{name}.js"] = js.strip()
        return files

    # ==================================================================
    # Phase 1 — Routes + Controllers
    # ==================================================================

    def generate_migrations(self) -> dict[str, str]:
        # Sequelize syncs automatically in this setup
        return {}

    def generate_routes(self) -> dict[str, str]:
        files = {}
        ctrl_routes: dict[str, list] = {}
        for route in self.routes:
            cn = route["controller"]["name"]
            ctrl_routes.setdefault(cn, []).append(route)

        route_mounts = []
        for ctrl in self.controllers:
            ctrl_name = ctrl["name"]
            snake = _to_snake(ctrl_name.replace("Controller", ""))
            routes = ctrl_routes.get(ctrl_name, [])
            lines = []
            for route in routes:
                method = route["method"].lower()
                path = route["path"].replace("{id}", ":id")
                if path.startswith("/api"):
                    path = path[4:] or "/"
                fn_name = route["controller"]["function"]
                lines.append(f"router.{method}('{path}', {ctrl_name}.{fn_name});")
            lines_str = "\n".join(lines)
            js = f"""const express = require('express');
const router = express.Router();
const {ctrl_name} = require('../controllers/{ctrl_name}');
// const {{ authenticate }} = require('../middleware/auth');  // uncomment to enable auth

{lines_str}

module.exports = router;
"""
            files[f"src/routes/{snake}.js"] = js.strip()
            route_mounts.append({
                "mount_path": "/api",
                "require_path": f"./routes/{snake}"
            })

        # app.js
        template = env.get_template("app.js.jinja2")
        js = template.render(routes=route_mounts)
        files["src/app.js"] = js.strip()
        
        index_js = """const app = require('./app');
let port = process.env.PORT || 3000;

// Parse CLI arguments for --port=XXXX
process.argv.slice(2).forEach(arg => {
    if (arg.startsWith('--port=')) {
        port = arg.split('=')[1];
    }
});

app.listen(port, () => {
    console.log(`Server running on port ${port}`);
});
"""
        files["src/index.js"] = index_js.strip()

        files["package.json"] = """{
  "name": "express-api-service",
  "version": "1.0.0",
  "description": "Generated API Service",
  "main": "src/index.js",
  "scripts": {
    "start": "node src/index.js",
    "dev": "nodemon src/index.js",
    "test": "jest"
  },
  "dependencies": {
    "cors": "^2.8.5",
    "express": "^4.21.0",
    "sequelize": "^6.37.0",
    "sqlite3": "^5.1.7"
  },
  "devDependencies": {
    "jest": "^29.7.0",
    "nodemon": "^3.1.0",
    "supertest": "^7.0.0"
  }
}"""

        return files

    def generate_controllers(self) -> dict[str, str]:
        files = {}
        template = env.get_template("controller.js.jinja2")
        for ctrl in self.controllers:
            ctrl_name = ctrl["name"]
            model_name = ctrl.get("model", "")
            functions = ctrl.get("functions", [])
            
            for fn in functions:
                if "actions" in fn and str(fn.get("ai_inject_logic", "")).lower() != "standard":
                    fn["action_code"] = self._generate_action_steps_js(fn["actions"], model_name)
                    
            js = template.render(model_name=model_name, functions=functions)
            files[f"src/controllers/{ctrl_name}.js"] = js.strip()
        return files

    def _generate_action_steps_js(self, actions: list, model: str) -> str:
        lines = []
        for action in actions:
            step = action.get("step", "")
            if step == "check_condition":
                msg = action["on_true_message"]
                code = action["on_true_code"]
                cond = action["condition"]
                js_cond = _translate_condition_js(cond)
                lines.append(f"if ({js_cond}) return res.status({code}).json({{ message: '{msg}' }});")
            elif step == "check_relation_empty":
                rel = action["relation_model"]
                code = action["on_fail_code"]
                msg = action["on_fail_message"]
                lines.append(
                    f"const related = await {rel}.count({{ where: {{ id: req.params.id }} }});\n"
                    f"if (related > 0) return res.status({code}).json({{ message: '{msg}' }});"
                )
            elif step == "set_field":
                field = action["field"]
                value = "new Date()" if action["value"] == "now" else f"'{action['value']}'"
                lines.append(f"record.{field} = {value};\nawait record.save();")
            elif step == "delete_record":
                lines.append(
                    f"const record = await {model}.findByPk(req.params.id);\n"
                    f"await record.destroy();\nres.status(204).send();"
                )
            elif step == "dispatch_job":
                job = action["job_name"]
                lines.append(f"// Dispatch job: {job}\n// await {job}Queue.add(req.body);")

        if not any("res.status" in l or "res.json" in l for l in lines):
            lines.append(f"const record = await {model}.findByPk(req.params.id);\nres.json(record);")
        return "\n".join(lines)

    def generate_tests_phase1(self) -> dict[str, str]:
        test_blocks = []
        for route in self.routes:
            ctrl_name = route["controller"]["name"]
            fn_name = route["controller"]["function"]
            method = route.get("method", "get").lower()
            path = route.get("path", "")
            
            ctrl = next((c for c in self.controllers if c["name"] == ctrl_name), None)
            if not ctrl: continue
            
            fn = next((f for f in ctrl.get("functions", []) if f["name"] == fn_name), None)
            if not fn: continue
            
            logic = fn.get("ai_inject_logic")
            if not logic or str(logic).lower() == "standard" or "actions" in fn:
                test_path = path.replace(":id", "1")
                if fn_name == "index":
                    test_blocks.append(f"  test('GET {path} - returns 200 array', async () => {{\n    const res = await request(app).get('{test_path}');\n    expect(res.statusCode).toEqual(200);\n    expect(Array.isArray(res.body)).toBeTruthy();\n  }});")
                elif fn_name == "store":
                    test_blocks.append(f"  test('POST {path} - returns 201', async () => {{\n    const res = await request(app).post('{test_path}').send({{}});\n    expect([201, 400, 500]).toContain(res.statusCode);\n  }});")
                elif fn_name == "show":
                    test_blocks.append(f"  test('GET {path} - returns 200 or 404', async () => {{\n    const res = await request(app).get('{test_path}');\n    expect([200, 404]).toContain(res.statusCode);\n  }});")
                elif fn_name == "update":
                    test_blocks.append(f"  test('PUT {path} - returns 200 or 404', async () => {{\n    const res = await request(app).put('{test_path}').send({{}});\n    expect([200, 400, 404, 500]).toContain(res.statusCode);\n  }});")
                elif fn_name == "destroy":
                    test_blocks.append(f"  test('DELETE {path} - returns 200 or 404', async () => {{\n    const res = await request(app).delete('{test_path}');\n    expect([200, 204, 404, 500]).toContain(res.statusCode);\n  }});")

        template = env.get_template("api.test.js.jinja2")
        js = template.render(standard_tests=test_blocks)
        return {"tests/api.test.js": js.strip()}

    # ==================================================================
    # Phase 2
    # ==================================================================

    def build_ai_inject_prompt(self, controller_name, function_name, ai_inject_logic, model_name):
        model = self.models.get(model_name, {})
        cols = model.get("columns", [])
        col_desc = ", ".join(f"{c['name']} ({c.get('type','string')})" for c in cols)
        all_models = ", ".join(self.models.keys())
        return (
            f"You are an Express.js + Sequelize expert. Generate ONLY the JavaScript "
            f"function body for the following async controller method.\n\n"
            f"Controller: {controller_name}\nFunction: {function_name}\n"
            f"Task: {ai_inject_logic}\n\n"
            f"Current Model: {model_name} — Columns: {col_desc}\n"
            f"All Available Models in Project: {all_models}\n\n"
            f"Requirements:\n- Use async/await with Sequelize\n"
            f"- Use req, res parameters (already in scope)\n"
            f"- Do NOT use `req.models`. If you need to access any models, require them locally inside the function (e.g. `const Transaction = require('../models/Transaction');`)\n"
            f"- No function signature, only the body\n"
            f"- No markdown, pure JS code only\n"
        )

    def inject_ai_code(self, file_path, function_name, generated_code):
        with open(file_path, "r") as f:
            content = f.read()
        pattern = (
            rf"(exports\.{re.escape(function_name)} = async \(req, res\) => \{{\n)"
            rf"(.*?// TODO: ai_inject_logic.*?)\n(\}};)"
        )
        indented = "\n".join("  " + l for l in generated_code.strip().splitlines())
        replacement = rf"\g<1>{indented}\n\g<3>"
        new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
        with open(file_path, "w") as f:
            f.write(new_content)


def _to_snake(s: str) -> str:
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).lower()

def _translate_condition_js(cond: str) -> str:
    cond = re.sub(r'\b([a-z]\w*)->(\w+)', r'record.\2', cond)
    cond = re.sub(r'(\w+)\s*!=\s*null', r'\1 !== null', cond)
    cond = re.sub(r'(\w+)\s*==\s*null', r'\1 === null', cond)
    return cond
