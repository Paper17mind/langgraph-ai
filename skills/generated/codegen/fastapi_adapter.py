_SA_TYPE_MAP = {
    "bigInteger": "BigInteger",
    "integer":    "Integer",
    "string":     "String",
    "text":       "Text",
    "boolean":    "Boolean",
    "date":       "Date",
    "datetime":   "DateTime",
    "decimal":    "Numeric",
    "float":      "Float",
    "json":       "JSON",
}


def _py_type(col: dict) -> str:
    t = _TYPE_MAP_PY.get(col.get("type", "string"), "str")
    if col.get("nullable"):
        return f"Optional[{t}]"
    return t


def _sa_type(col: dict) -> str:
    t = _SA_TYPE_MAP.get(col.get("type", "string"), "String")
    if t == "String" and col.get("length"):
        t = f"String({col['length']})"
    return t


