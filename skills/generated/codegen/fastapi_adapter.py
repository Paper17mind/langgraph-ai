    def generate_routes(self) -> dict[str, str]:
        files = {}
        # Group by controller → router file
        ctrl_routes: dict[str, list] = {}
        for route in self.routes:
            cn = route["controller"]["name"]
            ctrl_routes.setdefault(cn, []).append(route)

        for ctrl in self.controllers:
            ctrl_name = ctrl["name"]
            model_name = ctrl.get("model", "")
            routes = ctrl_routes.get(ctrl_name, [])
            route_lines = []
            for route in routes:
                method = route["method"]
                path = route["path"]
                fn_name = route["controller"]["function"]
                access = route.get("access", {})
                roles = access.get("roles", [])
                dep = ""
